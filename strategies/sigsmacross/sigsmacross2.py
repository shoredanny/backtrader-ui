'''The minimal SMA crossover signal strategy from the README (the
sample script ran it at import time). YHOO is no longer on Yahoo: the
offline yhoo file is used instead.

Ported from backtrader/samples/sigsmacross/sigsmacross2.py.
'''
from datetime import datetime
import backtrader as bt


class SmaCross(bt.SignalStrategy):
    def __init__(self):
        sma1 = bt.ind.SMA(period=10)
        sma2 = bt.ind.SMA(period=30)
        crossover = bt.ind.CrossOver(sma1, sma2)
        self.signal_add(bt.SIGNAL_LONG, crossover)


